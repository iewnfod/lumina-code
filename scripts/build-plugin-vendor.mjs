#!/usr/bin/env node
// Bundles the Office Tools plugin's document engines (npm `docx` +
// `pptxgenjs`, both MIT and dependency-light) into two self-contained
// single-file ESM modules under src/plugins/officeToolsVendor/ — the
// plugin (src/plugins/officeTools.js) reaches them at runtime through a
// DYNAMIC relative import (`await import("./vendor/docx.mjs")`), which
// the opencode server executes from the installed plugin directory.
//
// Generated-but-committed, the gen:icons doctrine: CI never runs this
// (the bundles are source-controlled); rerun manually after bumping the
// devDependencies:
//
//   pnpm gen:office-vendor
//
// Platform notes: format esm + platform node keeps `node:*` builtins
// external (the server runtime provides them) while inlining everything
// else; minify keeps each bundle small enough to write through the fs
// API on every plugin install (the diff-gate skips identical writes).
import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT_DIR = join(REPO_ROOT, "src", "plugins", "officeToolsVendor");

const BANNER = "// GENERATED by scripts/build-plugin-vendor.mjs (pnpm gen:office-vendor) — do not edit by hand.\n";

/** One engine bundle: a single default export carrying the library's
 * namespace, so the plugin consumes one stable shape regardless of the
 * library's own ESM/CJS flavor. */
async function bundleEngine(name, importExpression) {
  const result = await build({
    stdin: {
      // The wrapper makes the bundle's consumer contract uniform:
      // `const Lib = (await import("./vendor/<name>.mjs")).default`.
      contents: `${importExpression}\nexport default Lib;\n`,
      resolveDir: REPO_ROOT,
      loader: "js",
    },
    format: "esm",
    platform: "node",
    target: "es2022",
    bundle: true,
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "warning",
  });
  const text = result.outputFiles[0].text;
  if (!text.trim()) throw new Error(`empty bundle for ${name}`);
  return text;
}

await mkdir(OUT_DIR, { recursive: true });

const docx = await bundleEngine("docx", 'import * as Lib from "docx";');
await writeFile(join(OUT_DIR, "docx.mjs"), BANNER + docx, "utf8");

const pptxgenjs = await bundleEngine("pptxgenjs", 'import * as Lib from "pptxgenjs";');
await writeFile(join(OUT_DIR, "pptxgenjs.mjs"), BANNER + pptxgenjs, "utf8");

const kb = (s) => `${(s.length / 1024).toFixed(0)} KB`;
console.log(`→ src/plugins/officeToolsVendor/docx.mjs (${kb(docx)})`);
console.log(`→ src/plugins/officeToolsVendor/pptxgenjs.mjs (${kb(pptxgenjs)})`);
